-- DIVIPOLA: catálogo oficial de departamentos y municipios de Colombia (DANE), con sus códigos.
-- Fuente: datos.gov.co, conjunto «gdxc-w37w» (DIVIPOLA - Códigos municipios), nombres tal como los publica el DANE.
-- 33 departamentos y 1.122 entidades: 1.103 municipios, 18 áreas no municipalizadas y 1 isla.
-- Es un catálogo global y de solo lectura (como `razas`): no lleva `finca_id` porque no pertenece a ninguna finca y
-- nadie escribe en él desde la app. Sirve para traducir los códigos DANE del libro genealógico a nombres.

create table public.divipola_departamentos (
  codigo text primary key check (codigo ~ '^[0-9]{2}$'),
  nombre text not null unique
);

create table public.divipola_municipios (
  codigo text primary key check (codigo ~ '^[0-9]{5}$'),
  departamento_codigo text not null references public.divipola_departamentos (codigo),
  nombre text not null,
  tipo text not null check (tipo in ('Municipio', 'Área no municipalizada', 'Isla')),
  constraint divipola_municipio_en_su_departamento check (left(codigo, 2) = departamento_codigo)
);

create index divipola_municipios_departamento_idx on public.divipola_municipios (departamento_codigo);

comment on table public.divipola_departamentos is 'DIVIPOLA (DANE): departamentos de Colombia con su código de 2 dígitos. Catálogo global de solo lectura.';
comment on table public.divipola_municipios is 'DIVIPOLA (DANE): municipios, áreas no municipalizadas e isla, con su código de 5 dígitos (los 2 primeros son el departamento). Catálogo global de solo lectura.';

alter table public.divipola_departamentos enable row level security;
alter table public.divipola_municipios enable row level security;

create policy divipola_departamentos_select on public.divipola_departamentos for select to authenticated using (true);
create policy divipola_municipios_select on public.divipola_municipios for select to authenticated using (true);

revoke all on public.divipola_departamentos, public.divipola_municipios from public, anon, authenticated;
grant select on public.divipola_departamentos, public.divipola_municipios to authenticated;

